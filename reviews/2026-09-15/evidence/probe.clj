(def E "")
(defn vis [s] (-> (str s) (str/replace E "<ESC>")))
(defmacro probe [label & body]
  `(println (str "## " ~label " => ")
            (try (vis (pr-str (do ~@body)))
                 (catch Throwable e# (str "THROWS " (.getName (class e#)) ": " (.getMessage e#))))))

